GLYPHS = {k: v.split("/") for k, v in _RAW.items()}
W, H, ADV = 5, 7, 6            # glyph size and advance, in font pixels


def glyph(ch: str) -> list[str]:
    return GLYPHS.get(ch.upper(), ["....."] * H)


def text_width(text: str, px: float) -> float:
    return max(0, len(text) * ADV - 1) * px


def text_path(text: str, x: float, y: float, px: float, py: float | None = None) -> str:
    """One SVG path (horizontal pixel runs) for `text`, top-left at x,y."""
    py = px if py is None else py
    d = []
    for i, ch in enumerate(text):
        rows = glyph(ch)
        gx = x + i * ADV * px
        for r, row in enumerate(rows):
            c = 0
            while c < W:
                if row[c] != "#":
                    c += 1
                    continue
                e = c
                while e < W and row[e] == "#":
                    e += 1
                d.append(f"M{gx + c * px:g} {y + r * py:g}h{(e - c) * px:g}v{py:g}h{-(e - c) * px:g}z")
                c = e
    return "".join(d)
